template<typename T, std::size_t N>
T EvaluateChebyshev(const std::array<T, N>& coefficients, T x)
{
  T b1 = T(0);
  T b2 = T(0);
  for (std::size_t i = N - 1; i > 0; --i) {
    const T b0 = T(2) * x * b1 - b2 + coefficients[i];
    b2 = b1;
    b1 = b0;
  }
  return x * b1 - b2 + coefficients[0];
}

