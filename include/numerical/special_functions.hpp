template<typename T>
T SiMinusHalfPi(T x)
{
  static_assert(std::is_floating_point_v<T>,
                "SiMinusHalfPi requires a floating-point type");

  constexpr T half_pi = std::numbers::pi_v<T> / T(2);
  if (std::isnan(x)) {
    return x;
  }
  if (std::isinf(x)) {
    return std::signbit(x) ? -T(2) * half_pi : T(0);
  }

  const T abs_x = std::abs(x);
  if (abs_x <= T(4)) {
    return numerical_special_functions_detail::SiCore(x) - half_pi;
  }

  const T tail = numerical_special_functions_detail::SiTail(abs_x);
  return std::signbit(x) ? -T(2) * half_pi - tail : tail;
}

template<typename T>
T Si(T x)
{
  static_assert(std::is_floating_point_v<T>,
                "Si requires a floating-point type");

  if (std::isnan(x)) {
    return x;
  }
  if (std::isinf(x)) {
    return std::copysign(std::numbers::pi_v<T> / T(2), x);
  }

  const T abs_x = std::abs(x);
  if (abs_x <= T(4)) {
    return numerical_special_functions_detail::SiCore(x);
  }
  const T value = std::numbers::pi_v<T> / T(2) +
    numerical_special_functions_detail::SiTail(abs_x);
  return std::copysign(value, x);
}

